// Generate constructor declarations from the same pinned schema as the runtime.
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';
import schema from '../src/schema/telegram.json' with { type: 'json' };
import { camel, gramClassName } from '../src/requests.js';
import { resolvableTypes } from '../src/tl-resolution.js';
import { mediaInputTypes } from '../src/tl-media.js';

const quote = (value) => JSON.stringify(value);
const directory = fileURLToPath(
  new globalThis.URL('../src/api-types/', import.meta.url)
);
const primitives = {
  int: 'number',
  double: 'number',
  long: 'LongValue',
  string: 'string',
  bytes: 'Uint8Array',
  int128: 'FixedInteger',
  int256: 'FixedInteger',
  Bool: 'boolean',
  true: 'boolean',
  Object: 'TlObject',
  X: 'TlObject',
  '!X': 'TlObject',
};
const constructors = new Map(
  schema.constructors.map((entry) => [entry.predicate, entry])
);

function fieldType(type) {
  const vector = /^(?:Vector|vector)<(.+)>$/.exec(type);
  if (vector) {
    return `Array<${fieldType(vector[1])}>`;
  }
  if (type === 'InputMessage') {
    return 'number | TlObject<"InputMessage" | "Message">';
  }
  if (mediaInputTypes.has(type)) {
    return `ResolvableMedia<${quote(type)}>`;
  }
  if (resolvableTypes.has(type)) {
    return `ResolvablePeer<${quote(type)}>`;
  }
  return (
    primitives[type] ??
    `TlObject<${quote(constructors.get(type)?.type ?? type)}>`
  );
}

function declaration(definition) {
  const path = gramClassName(definition.method ?? definition.predicate).split(
    '.'
  );
  const name = path.pop();
  const namespace = path.join('.') || 'root';
  const fields = definition.params.filter((field) => field.type !== '#');
  const parameters = fields.map((field) => {
    const optional = /^\w+\.\d+\?(.+)$/.exec(field.type);
    return `${camel(field.name)}${optional ? '?' : ''}: ${fieldType(optional?.[1] ?? field.type)};`;
  });
  const defaulted = fields.some(
    (field) =>
      field.name === 'random_id' &&
      ['int', 'long', 'Vector<long>'].includes(field.type)
  );
  const value = `TlClass<${quote([...path, name].join('.'))}, ${quote(definition.type)}, {${parameters.join('\n')}}${defaulted ? ', "randomId"' : ''}>`;
  return { namespace, member: `${name}: ${value};` };
}

async function generate() {
  const files = new Map();
  const namespaces = new Map();
  for (const definition of [...schema.methods, ...schema.constructors]) {
    const { namespace, member } = declaration(definition);
    const members = namespaces.get(namespace) ?? [];
    members.push(member);
    namespaces.set(namespace, members);
  }
  const imports = [];
  const properties = [];
  for (const [namespace, members] of namespaces) {
    const groups = [];
    let group = [];
    let lines = 0;
    for (const member of members) {
      const formatted = await format(`interface Fields {${member}}`, {
        parser: 'typescript',
        singleQuote: true,
      });
      const body = formatted.split('\n').slice(1, -2).join('\n');
      const count = body.split('\n').length;
      if (lines + count > 1300 && group.length) {
        groups.push(group);
        group = [];
        lines = 0;
      }
      group.push(body);
      lines += count;
    }
    groups.push(group);
    const types = groups.map((entries, index) => {
      const name = `${namespace[0].toUpperCase()}${namespace.slice(1)}Classes${index}`;
      const file = `${namespace}-${index}.d.ts`;
      const content =
        '// Generated by scripts/update-api-types.mjs; do not edit.\n' +
        "import type { TlClass, TlObject, LongValue, FixedInteger, ResolvablePeer, ResolvableMedia } from '../api-classes.js';\n" +
        `export interface ${name} {\n${entries.join('\n')}\n}\n`;
      files.set(file, content);
      imports.push(
        `import type { ${name} } from './api-types/${namespace}-${index}.js';`
      );
      return name;
    });
    properties.push(
      namespace === 'root'
        ? types.join(' & ')
        : `{ ${namespace}: ${types.join(' & ')} }`
    );
  }
  const root = `${imports.join('\n')}\nexport declare const Api: ${properties.join(' & ')};\n`;
  return { files, root };
}

const result = await generate();
const check = process.argv.includes('--check');
if (!check) {
  await mkdir(directory, { recursive: true });
}
for (const [file, content] of result.files) {
  const formatted = await format(content, {
    parser: 'typescript',
    singleQuote: true,
  });
  const path = `${directory}${file}`;
  if (check) {
    if ((await readFile(path, 'utf8')) !== formatted) {
      throw new Error(`Stale generated API declaration: ${file}`);
    }
  } else {
    await writeFile(path, formatted);
  }
}
for (const file of await readdir(directory)) {
  if (!result.files.has(file)) {
    if (check) {
      throw new Error(`Unexpected generated API declaration: ${file}`);
    }
    await rm(`${directory}${file}`);
  }
}
const rootPath = fileURLToPath(
  new globalThis.URL('../src/api.d.ts', import.meta.url)
);
const root = await format(
  `// Generated by scripts/update-api-types.mjs; do not edit.\n${result.root}`,
  { parser: 'typescript', singleQuote: true }
);
if (check) {
  if ((await readFile(rootPath, 'utf8')) !== root) {
    throw new Error('Stale generated API namespace');
  }
} else {
  await writeFile(rootPath, root);
}
console.log(
  `${check ? 'Checked' : 'Generated'} declarations for ${schema.methods.length + schema.constructors.length} classes in ${result.files.size} bounded files`
);
